import { expect, test } from '@playwright/test'

test('LISA abre tarefa e só conclui com todos os critérios DONE', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Time LISA' })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir LISA-106:', exact: false }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByRole('heading', { name: 'Criar fluxo de novo compromisso' })).toBeVisible()
  await dialog.getByRole('button', { name: 'Concluir e entregar' }).click()
  await expect(dialog.getByRole('alert')).toContainText('critérios de pronto')
  await expect(dialog.getByText('IN PROGRESS', { exact: true })).toBeVisible()
  await dialog.getByRole('checkbox', { name: 'Critérios de aceitação atendidos' }).check()
  await dialog.getByRole('checkbox', { name: 'Testes e acessibilidade verificados' }).check()
  await dialog.getByRole('checkbox', { name: 'Integrada, utilizável e pronta para entrega' }).check()
  await dialog.getByRole('button', { name: 'Concluir e entregar' }).click()
  await expect(dialog.getByText('DONE', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Entrega concluída com os critérios atendidos.')).toBeVisible()
  await expect(dialog.getByRole('checkbox').first()).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  expect(errors).toEqual([])
})

test('reprovação exige motivo e replanejamento preserva ID/histórico e limpa critérios', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Abrir LISA-106:', exact: false }).click()
  const dialog = page.getByRole('dialog')
  for (const checkbox of await dialog.getByRole('checkbox').all()) await checkbox.check()
  await dialog.getByRole('button', { name: 'Reprovar na validação' }).click()
  await dialog.getByRole('button', { name: 'Registrar reprovação' }).click()
  await expect(dialog.getByText('Descreva o motivo com pelo menos 8 caracteres.').first()).toBeVisible()
  await dialog.getByLabel('O que falhou na validação?').fill('Teste de edição identificou perda do título.')
  await dialog.getByRole('button', { name: 'Registrar reprovação' }).click()
  await expect(dialog.getByText('REJECTED', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: 'Replanejar', exact: true }).click()
  await expect(dialog.getByText('TODO', { exact: true })).toBeVisible()
  await expect(dialog.getByText('LISA-106 · Agenda e lembretes', { exact: true })).toBeVisible()
  await expect(dialog.getByText('Teste de edição identificou perda do título.', { exact: true })).toBeVisible()
  for (const checkbox of await dialog.getByRole('checkbox').all()) await expect(checkbox).not.toBeChecked()
  await dialog.getByText('Histórico da tarefa', { exact: false }).click()
  await expect(dialog.getByText(/Movida de IN PROGRESS para REJECTED/)).toBeVisible()
  await expect(dialog.getByText(/Replanejada após reprovação/)).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: 'Abrir LISA-106:', exact: false }).click()
  await expect(page.getByRole('dialog').getByText('IN PROGRESS', { exact: true })).toBeVisible()
})
